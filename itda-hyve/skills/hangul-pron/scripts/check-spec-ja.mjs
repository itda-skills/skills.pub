// SPEC 규칙 준수 검사 (일본어) — 이 스킬 일본어 파트의 정본 지표.
//
// 영어·중국어 쪽과 같은 원칙이다: **문자열 일치가 아니라 규칙의 관찰 가능한 결과**를 본다.
// SPEC §2-3 이 J1~J7 예시를 완전 표기로 적어 두었으므로 그 예시들은 exact 로 잡되,
// 규칙이 **자모 하나**를 말하는 것(J1 어두/어중, J3 받침)은 자모 단위로 본다.
//
// 사용: node check-spec-ja.mjs [--verbose]

import { transcribeJa } from './ja.mjs';

const V = process.argv.includes('--verbose');
const strip = (s) => s.replace(/\{([^}=]*)=[^}]*\}/g, '$1');

const CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ';
const JONG = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ';
const jamo = (ch) => {
  const o = ch.charCodeAt(0) - 0xac00;
  return (o < 0 || o > 11171) ? null : { cho: CHO[Math.floor(o / 588)], jong: JONG[o % 28] };
};
const eq = (s) => (out) => out === s;
/** n번째 글자(기호 제외)의 첫소리가 이 자모인가 */
const onsetAt = (i, c) => (out) => jamo(strip(out).replace(/\s/g, '')[i])?.cho === c;
/** 종성이 이 자모인 글자가 있는가 */
const coda = (c) => (out) => [...strip(out)].some((ch) => jamo(ch)?.jong === c);
const mark = (k) => (out) => [...out.matchAll(/\{[^}=]*=([^}]*)\}/g)].some((m) => m[1].includes(k));
const has = (re) => (out) => re.test(out);
const and = (...fs) => (out) => fs.every((f) => f(out));

// 검사 항목: [규칙, 가나, 판정, 설명] — 예시는 SPEC §2-3 표에서 그대로 가져왔다.
const CASES = [
  // J1 — 어두 か·た행은 ㅋ·ㅌ, 어중은 ㄲ·ㄸ. 촉음 받침 뒤는 예외(받침이 이미 긴장을 만든다).
  ['J1', 'かわいい',  eq('카와이ー'),                  '어두 か → ㅋ'],
  ['J1', 'いく',      eq('이꾸'),                      '어중 く → ㄲ'],
  ['J1', 'はこう',    eq('하꼬ー'),                    '어중 こ → ㄲ'],
  ['J1', 'たべよう',  and(onsetAt(0, 'ㅌ'), eq('타{베=v}요ー')), '어두 た → ㅌ'],
  ['J1', 'ひとくち',  and(onsetAt(1, 'ㄸ'), eq('히또꾸치')),     '어중 と → ㄸ'],
  ['J1a', 'ちょっと', eq('촛토'),                      'ㅅ받침 뒤는 어두형 ㅌ'],
  ['J1a', 'まって',   eq('맛테'),                      'ㅅ받침 뒤는 어두형 ㅌ'],
  ['J1a', 'ゆっくり', eq('육꾸리'),                    'ㄱ받침 뒤는 된소리 (경음화)'],
  ['J1a', 'いっぱい', eq('입빠이'),                    'ㅂ받침 뒤는 된소리 (경음화)'],
  ['J1b', 'さんぽ',   eq('삼뽀'),                      'ぱ행도 어중에서 된소리'],
  ['J1b', 'ページ',   has(/^페/),                      'ぱ행 어두는 ㅍ'],

  // J2 — 탁음은 청음 한글 + ˚. ぱ행은 반탁음이라 기호가 없다.
  ['J2', 'ごはん',    eq('{고=v}항'),                  'が행 → ˚'],
  ['J2', 'だめ',      eq('{다=v}메'),                  'だ행 → ˚'],
  ['J2', 'ページ',    and(mark('v'), has(/^페/)),      'じ 는 ˚, ぺ 는 기호 없음'],

  // J3 — ん 은 뒤 자음에 맞춘 받침
  ['J3', 'ごはん',    coda('ㅇ'),                      '어말 ん → ㅇ'],
  ['J3', 'さんぽ',    coda('ㅁ'),                      'ぱ행 앞 ん → ㅁ'],
  ['J3', 'ごめんね',  and(eq('{고=v}멘네'), coda('ㄴ')), 'な행 앞 ん → ㄴ'],
  ['J3', 'でんき',    eq('{뎅=v}끼'),                  'か행 앞 ん → ㅇ'],

  // J4 — 장음은 반드시 ー. **길이가 뜻을 바꾼다.**
  ['J4', 'おいしい',  eq('오이시ー'),                  'い단+い → ー (お+い 는 장음 아님)'],
  ['J4', 'たべよう',  has(/ー$/),                      'お단+う → ー'],
  ['J4', 'ぎゅーして', has(/ー/),                      'ー 는 그대로'],

  // J5 — つ 츠, ふ 후 (기호 없음)
  ['J5', 'くつ',      eq('쿠츠'),                      'つ → 츠'],
  ['J5', 'おふろ',    eq('오후로'),                    'ふ → 후'],

  // J6 — 조사 を 오, は 와, へ 에. 호흡이 끊기므로 앞말에서 뗀다.
  ['J6', 'ごはんを',  eq('{고=v}항 오'),               'を → 오, 떼어 적는다'],
  ['J6', 'これは',    eq('코레 와'),                   'は → 와'],
  ['J6', 'うちへ',    eq('우치 에'),                   'へ → 에'],
  ['J6', 'この',      eq('코노'),                      'この 의 の 는 조사가 아니다 — 떼지 않는다'],
  ['J6', 'さむいから',  eq('사무이까라'),               'から 를 떼면 か 가 어두가 돼 까→카 로 뒤집힌다 — 떼지 않는다'],
  ['J6', 'はを',        eq('하 오'),                    '歯を 의 は 는 조사가 아니다 — 와 로 읽지 않는다'],
  ['J6', 'ごはんをたべよう', eq('{고=v}항 오 타{베=v}요ー'), '띄어쓰기가 없어도 を 에서 끊어 같은 결과를 낸다'],

  // J7 — 촉음 받침은 뒤 자음에 동화
  ['J7', 'がっこう',  eq('{각=v}꼬ー'),                'か행 앞 → ㄱ받침'],
  ['J7', 'いっぱい',  coda('ㅂ'),                      'ぱ행 앞 → ㅂ받침'],
  ['J7', 'ちょっと',  coda('ㅅ'),                      '그 외 → ㅅ받침'],
  ['J7', 'いっしょ',  eq('잇쇼'),                      'さ행 앞 → ㅅ받침'],

  // J8 — ㅈ·ㅊ 뒤에는 반모음을 적지 않는다 (한국어에서 자/쟈·초/쵸가 같은 소리)
  ['J8', 'じょうず',  eq('{조=v}ー{즈=v}'),            'じょ → 조 (죠 가 아니다)'],
  ['J8', 'おもちゃ',  eq('오모차'),                    'ちゃ → 차 (챠 가 아니다)'],
  ['J8', 'いっしょ',  eq('잇쇼'),                      'ㅅ 뒤는 반모음을 적는다 — 쇼'],
];

const byRule = new Map();
let pass = 0;
for (const [rule, input, ok, why] of CASES) {
  const out = transcribeJa(input);
  const good = ok(out);
  if (good) pass++;
  if (!byRule.has(rule)) byRule.set(rule, [0, 0]);
  const r = byRule.get(rule);
  r[1]++; if (good) r[0]++;
  if (V || !good) console.log(`  ${good ? '✓' : '✗'} [${rule}] ${input.padEnd(10)} → ${out.padEnd(20)} ${why}`);
}

console.log(`\nSPEC 규칙 준수(일본어) ${pass}/${CASES.length} (${(pass / CASES.length * 100).toFixed(0)}%)`);
for (const [rule, [a, b]] of byRule) console.log(`  ${rule.padEnd(4)} ${a}/${b}`);
process.exit(pass === CASES.length ? 0 : 1);
